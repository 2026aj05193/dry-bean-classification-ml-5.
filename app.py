"""Streamlit interface for the trained Dry Bean classifiers."""
from pathlib import Path
import json
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report
)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"
st.set_page_config(page_title="Dry Bean Classifier", page_icon="🫘", layout="wide")
st.title("🫘 Dry Bean Variety Classification")
st.write("Compare five trained classifiers using geometric measurements of dry beans.")

required = [
    "logistic_regression.joblib", "decision_tree.joblib", "k_nearest_neighbors.joblib",
    "gaussian_naive_bayes.joblib", "support_vector_machine.joblib",
    "label_encoder.joblib", "metadata.json"
]
missing = [f for f in required if not (MODEL_DIR / f).exists()]
if missing:
    st.error("Trained model files are missing: " + ", ".join(missing))
    st.info("Run `python train_models.py` locally or in BITS Virtual Lab before starting the app.")
    st.stop()

metadata = json.loads((MODEL_DIR / "metadata.json").read_text())
encoder = joblib.load(MODEL_DIR / "label_encoder.joblib")
model_files = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "k_nearest_neighbors.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib",
}
models = {name: joblib.load(MODEL_DIR / file) for name, file in model_files.items()}
features = metadata["features"]
target = metadata["target"]

st.sidebar.header("Evaluation settings")
selected_model = st.sidebar.selectbox("Choose classifier", list(models.keys()))
st.sidebar.caption("Upload a labelled test CSV containing all 16 feature columns and the Class target column.")
uploaded = st.file_uploader("Upload test data (CSV)", type=["csv"])
if uploaded is None:
    default_path = ROOT / "test_data.csv"
    if not default_path.exists():
        st.warning("No test_data.csv found. Run train_models.py first, or upload a labelled test CSV.")
        st.stop()
    df = pd.read_csv(default_path)
    st.caption("Using the held-out test_data.csv generated by train_models.py.")
else:
    df = pd.read_csv(uploaded)

missing_cols = [c for c in features + [target] if c not in df.columns]
if missing_cols:
    st.error("The uploaded CSV is missing required columns: " + ", ".join(missing_cols))
    st.stop()
if df.empty:
    st.warning("The uploaded CSV contains no rows.")
    st.stop()

try:
    X = df[features].apply(pd.to_numeric, errors="raise")
    y_true = encoder.transform(df[target].astype(str))
except Exception as exc:
    st.error(f"Could not prepare the uploaded data. Check numeric features and known target labels. Details: {exc}")
    st.stop()

model = models[selected_model]
y_pred = model.predict(X)
y_prob = model.predict_proba(X)
metrics = {
    "Accuracy": accuracy_score(y_true, y_pred),
    "AUC (macro OVR)": roc_auc_score(
        y_true, y_prob, multi_class="ovr", average="macro",
        labels=list(range(len(encoder.classes_)))
    ),
    "Precision (macro)": precision_score(y_true, y_pred, average="macro", zero_division=0),
    "Recall (macro)": recall_score(y_true, y_pred, average="macro", zero_division=0),
    "F1 (macro)": f1_score(y_true, y_pred, average="macro", zero_division=0),
    "MCC": matthews_corrcoef(y_true, y_pred),
}
st.subheader(f"Results: {selected_model}")
cols = st.columns(6)
for col, (label, value) in zip(cols, metrics.items()):
    col.metric(label, f"{value:.4f}")

left, right = st.columns(2)
with left:
    st.subheader("Confusion matrix")
    cm = confusion_matrix(y_true, y_pred, labels=list(range(len(encoder.classes_))))
    fig, ax = plt.subplots(figsize=(8, 6))
    im = ax.imshow(cm)
    ax.set_xticks(range(len(encoder.classes_)), encoder.classes_, rotation=45, ha="right")
    ax.set_yticks(range(len(encoder.classes_)), encoder.classes_)
    ax.set_xlabel("Predicted label")
    ax.set_ylabel("True label")
    fig.colorbar(im, ax=ax)
    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)
with right:
    st.subheader("Classification report")
    report = classification_report(
        y_true, y_pred, labels=list(range(len(encoder.classes_))),
        target_names=list(encoder.classes_), output_dict=True, zero_division=0
    )
    st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

st.subheader("Compare all five models on this uploaded test data")
rows = []
for name, fitted_model in models.items():
    pred = fitted_model.predict(X)
    prob = fitted_model.predict_proba(X)
    rows.append({
        "Model": name,
        "Accuracy": accuracy_score(y_true, pred),
        "AUC": roc_auc_score(y_true, prob, multi_class="ovr", average="macro",
                             labels=list(range(len(encoder.classes_)))),
        "Precision": precision_score(y_true, pred, average="macro", zero_division=0),
        "Recall": recall_score(y_true, pred, average="macro", zero_division=0),
        "F1": f1_score(y_true, pred, average="macro", zero_division=0),
        "MCC": matthews_corrcoef(y_true, pred),
    })
st.dataframe(pd.DataFrame(rows).set_index("Model").round(4), use_container_width=True)

st.subheader("Predictions")
output = df.copy()
output["Actual_Class"] = df[target].astype(str)
output["Predicted_Class"] = encoder.inverse_transform(y_pred)
output["Correct"] = output["Actual_Class"] == output["Predicted_Class"]
st.dataframe(output.head(100), use_container_width=True)
st.download_button("Download predictions CSV", output.to_csv(index=False).encode("utf-8"),
                   file_name="dry_bean_predictions.csv", mime="text/csv")
